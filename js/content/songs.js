const slug = (s) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

export const CATALOG = Object.entries(RAW).flatMap(([scene, list]) =>
  list.map(([artist, title, level, tags]) => ({ id: `${slug(artist)}--${slug(title)}`, artist, title, scene, level, tags: tags.split(' ') }))
);

const BY_ID = new Map(CATALOG.map((s) => [s.id, s]));
export const catalogSong = (id) => BY_ID.get(id);
